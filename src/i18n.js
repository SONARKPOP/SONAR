// Translate interface text emitted by App while preserving event handlers,
// values, keys, refs and third-party content that has no interface dictionary key.
export function localize(node,language){
 if(language==='ko')return node;
 if(typeof node==='string')return translate(node,language);
 if(Array.isArray(node))return node.map(child=>localize(child,language));
 if(!React.isValidElement(node))return node;
 if(node.props['data-no-translate'])return node;
 const props={};
 for(const key of ['aria-label','title','placeholder'])if(typeof node.props[key]==='string')props[key]=translate(node.props[key],language);
 if(node.props.children!==undefined)props.children=localize(node.props.children,language);
 return React.cloneElement(node,props);
}
